export const DICT = { en: EN, pt: PT };

let store = { lang: 'en' };

/** Connects t() to the reactive store that holds the language. */
export function bindStore(s) {
  store = s;
}

/** The language of this browser: Portuguese for pt, English for everything else. */
export function detectLang() {
  return String(navigator.language || 'en').toLowerCase().startsWith('pt') ? 'pt' : 'en';
}

export function t(key, vars = {}) {
  const lang = store.lang === 'pt' ? 'pt' : 'en';
  let s = DICT[lang][key] ?? EN[key];
  if (s == null) return '';
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
